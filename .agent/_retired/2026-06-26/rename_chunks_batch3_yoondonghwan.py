def validate():
    """매핑 검증."""
    print(f'전체 매핑: {len(MAPPING)}개')

    # 1. 옛 stem 중복 검사
    old_stems = list(MAPPING.keys())
    if len(old_stems) != len(set(old_stems)):
        print('ERROR: 옛 stem 중복')
        return False

    # 2. 새 stem 중복 검사
    new_stems = list(MAPPING.values())
    new_dup = defaultdict(list)
    for old, new in MAPPING.items():
        new_dup[new].append(old)
    conflicts = {k: v for k, v in new_dup.items() if len(v) > 1}
    if conflicts:
        print(f'WARNING: 새 stem 중복 {len(conflicts)}건')
        for new, olds in conflicts.items():
            print(f'  {new} <- {olds}')
        return False

    # 3. 한자 검사
    HANJA = re.compile(r'[\u4e00-\u9fff]')
    hanja_found = []
    for old, new in MAPPING.items():
        if HANJA.search(new):
            hanja_found.append((old, new))
    if hanja_found:
        print(f'WARNING: 한자 포함 {len(hanja_found)}건')
        for old, new in hanja_found[:5]:
            print(f'  {old} -> {new}')
        return False

    # 4. 길이 검사 (100자 이하)
    too_long = [(old, new) for old, new in MAPPING.items() if len(new) > 100]
    if too_long:
        print(f'WARNING: 100자 초과 {len(too_long)}건')
        for old, new in too_long[:5]:
            print(f'  {old} -> {new} ({len(new)}자)')
        return False

    # 5. 옛 청크 파일 존재 확인
    missing = []
    for old in MAPPING.keys():
        if not (SOURCE_DIR / f'{old}.md').exists():
            missing.append(old)
    if missing:
        print(f'WARNING: 옛 청크 파일 없음 {len(missing)}건')
        for old in missing[:10]:
            print(f'  {old}')
        return False

    print('검증 OK: 충돌 0, 한자 0, 길이 OK, 옛 청크 모두 존재')
    return True


def create_new_files(dry_run=True):
    """새 파일 생성 (옛 청크 본문 + frontmatter에 원본_chunk·새 stem 추가)."""
    print(f'\n[create_new_files] dry_run={dry_run}')
    created = 0
    for old_stem, new_stem in MAPPING.items():
        old_path = SOURCE_DIR / f'{old_stem}.md'
        new_path = SOURCE_DIR / f'{new_stem}.md'
        if not old_path.exists():
            print(f'  SKIP: {old_stem} 없음')
            continue
        if new_path.exists():
            print(f'  SKIP: {new_stem} 이미 존재')
            continue
        text = old_path.read_text(encoding='utf-8')
        # frontmatter에 원본_chunk 추가 (이미 있으면 갱신)
        if text.startswith('---\n'):
            end = text.index('\n---\n', 4)
            front = text[4:end]
            body = text[end+5:]
            if '원본_chunk:' not in front:
                front += f'\n원본_chunk: {old_stem}'
            new_text = f'---\n{front}\n---\n{body}'
        else:
            new_text = f'---\n원본_chunk: {old_stem}\n---\n{text}'
        if dry_run:
            print(f'  [DRY] {old_stem} -> {new_stem}')
        else:
            new_path.write_text(new_text, encoding='utf-8')
        created += 1
    print(f'  생성: {created}개')
    return created


def replace_wikilinks(dry_run=True):
    """sync/{민법,형법,헌법,_교재원문} 전체에서 옛 stem → 새 stem 치환."""
    print(f'\n[replace_wikilinks] dry_run={dry_run}')
    changed_files = 0
    total_replacements = 0
    for src in ['민법', '형법', '헌법', '_교재원문']:
        for f in (ROOT / src).rglob('*.md'):
            text = f.read_text(encoding='utf-8')
            new_text = text
            file_replacements = 0
            for old, new in MAPPING.items():
                if old in new_text:
                    count = new_text.count(old)
                    new_text = new_text.replace(old, new)
                    file_replacements += count
            if file_replacements > 0:
                if dry_run:
                    rel = f.relative_to(ROOT)
                    print(f'  [DRY] {rel}: {file_replacements}건')
                else:
                    f.write_text(new_text, encoding='utf-8')
                changed_files += 1
                total_replacements += file_replacements
    print(f'  변경 파일: {changed_files}, 총 치환: {total_replacements}')
    return changed_files, total_replacements


def move_old_to_trash(dry_run=True):
    """옛 청크 파일을 trash로 이동."""
    print(f'\n[move_old_to_trash] dry_run={dry_run}')
    if not dry_run:
        TRASH_BASE.mkdir(parents=True, exist_ok=True)
    moved = 0
    for old_stem in MAPPING.keys():
        old_path = SOURCE_DIR / f'{old_stem}.md'
        if not old_path.exists():
            print(f'  SKIP: {old_stem} 없음')
            continue
        trash_path = TRASH_BASE / f'{old_stem}.md'
        if dry_run:
            print(f'  [DRY] {old_stem} -> trash')
        else:
            shutil.move(str(old_path), str(trash_path))
        moved += 1
    print(f'  이동: {moved}개')
    return moved


def main():
    args = sys.argv[1:]
    mode = args[0] if args else '--help'

    if mode == '--validate':
        validate()
    elif mode == '--dry-run':
        if not validate():
            return 1
        create_new_files(dry_run=True)
        replace_wikilinks(dry_run=True)
        move_old_to_trash(dry_run=True)
    elif mode == '--run':
        if not validate():
            return 1
        print(f'\n=== 실제 실행 시작 ({datetime.now().isoformat()}) ===')
        create_new_files(dry_run=False)
        replace_wikilinks(dry_run=False)
        move_old_to_trash(dry_run=False)
        print(f'\n=== 완료 ({datetime.now().isoformat()}) ===')
    else:
        print('사용법: python rename_chunks_batch3_yoondonghwan.py [--validate|--dry-run|--run]')

    return 0


if __name__ == '__main__':
    sys.exit(main())
