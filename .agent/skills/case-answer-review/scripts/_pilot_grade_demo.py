"""_pilot_grade_demo.py — 비순환 채점 시연.

핵심: expected unit은 '모범답안'에서 추출(학생과 독립). 학생 답안은 그 기준으로 채점.
아래 EXPECTED는 민사사례연습1 p33 사례1 설문1(15점) '丙은 A토지 소유권을 취득하는가'의
모범답안 본문(논점정리→II 공유처분 효력→III 민법 제126조→IV 결론)에서만 추출(#1).
요건/쟁점/포섭 = LLM 구조화 산출(06b 방식)을 대표. 조문/판례 = 본문 명시분.
실행: python3 이파일
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _case_rubric import score_rubric_units  # noqa: E402

# ── 모범답안에서 추출한 정답 unit (학생 무관) ───────────────────────────────
EXPECTED = {
    "label": "丙의 A토지 소유권 취득 여부 — 甲 지분에 대한 민법 제126조 표현대리",
    "근거": ["§126"],  # 본문 명시. (지분처분 효력은 판례로 처리)
    "요건": ["기본대리권", "권한을 넘은 대리행위", "정당한 이유(선의·무과실)", "본인의 귀책"],
    "쟁점": ["공유자 무단처분의 효력(지분범위 내 유효)", "민법 제126조 표현대리 성립", "정당한 이유 입증책임"],
    "포섭_사실": ["공유물분할등기 신청권 수여", "등기신청 넘어 매매", "丙의 선의·무과실", "甲의 인감·서류 교부"],
    "결론": "인용",
    "keywords": ["대판 1994.12.2, 93다1596", "대판 1989.4.11, 88다카13219", "대판 1968.6.18, 68다694"],
}

# ── 학생 답안 2종 (모범답안과 별개로 작성된 것) ─────────────────────────────
STUDENT_GOOD = (
    "공유자 무단처분의 효력이 문제된다. 공유자 1인이 동의 없이 전부 처분해도 지분범위 내 유효하다(93다1596). "
    "甲 지분은 민법 제126조 표현대리 성립이 쟁점. 기본대리권으로 공유물분할등기 신청권 수여가 있었고, "
    "등기신청 넘어 매매한 것은 권한을 넘은 대리행위다. 丙의 선의·무과실과 甲의 인감·서류 교부라는 본인의 귀책이 인정된다. "
    "정당한 이유 입증책임은 유효 주장자에게 있다(68다694). 따라서 丙은 소유권을 취득하여 청구는 인용된다."
)
STUDENT_WEAK = "표현대리가 성립하는지 문제된다. 丙은 선의이므로 소유권을 취득하지 못하고 기각된다."


def show(name, student):
    r = score_rubric_units(student, [EXPECTED], unit_type="청구")
    print(f"\n=== {name} === 등급={r['grade']} 점수={r['score']} 제안={r['review_suggestions']}")
    for k, it in r["units"][0]["items"].items():
        print(f"    {k:12s}: {it['status']:4s} {it['score']}")


def main():
    print("[정답 unit] (모범답안에서 추출, 학생 무관)")
    print(f"  쟁점 {len(EXPECTED['쟁점'])} · 요건 {len(EXPECTED['요건'])} · 포섭사실 "
          f"{len(EXPECTED['포섭_사실'])} · 결론 {EXPECTED['결론']}")
    show("우수 학생 답안", STUDENT_GOOD)
    show("부실 학생 답안", STUDENT_WEAK)


if __name__ == "__main__":
    main()
