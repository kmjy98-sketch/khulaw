def run(src_name, book_id, year, segs):
    src = ROOT / src_name
    if not src.exists():
        print(f"[누락] 원본 없음: {src_name}")
        return
    reader = PdfReader(str(src))
    total = len(reader.pages)
    covered = []
    labels = [l for l, _, _ in segs]
    for _, s, e in segs:
        covered.extend(range(s, e + 1))
    miss = sorted(set(range(1, total + 1)) - set(covered))
    dup = len(covered) - len(set(covered))
    dlabel = len(labels) - len(set(labels))
    status = "OK" if not (miss or dup or dlabel) else "검증실패"
    print(f"\n[{book_id}] {src_name}  총{total}p  세그{len(segs)}  [{status}]")
    if miss:
        print(f"  ⚠ 미포함: {miss[:15]}{'...' if len(miss) > 15 else ''}")
    if dup:
        print(f"  ⚠ 중복 페이지 {dup}")
    if dlabel:
        print(f"  ⚠ 라벨 중복 {dlabel}")
    if status != "OK":
        print("  → 생성 건너뜀 (범위 수정 필요)")
        return
    for label, s, e in segs:
        w = PdfWriter()
        for p in range(s - 1, e):
            w.add_page(reader.pages[p])
        out = ROOT / f"{book_id}_{label}_{year}.pdf"
        with open(out, "wb") as f:
            w.write(f)
        mb = out.stat().st_size / (1024 * 1024)
        flag = "  ⚠>80MB" if mb > 80 else ""
        print(f"  [생성] {out.name}  p.{s}-{e} ({e - s + 1}p, {mb:.1f}MB){flag}")


if __name__ == "__main__":
    for src, bid, yr, segs in JOBS:
        run(src, bid, yr, segs)
